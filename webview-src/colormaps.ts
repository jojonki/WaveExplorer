function buildGrayscale(): [number, number, number][] {
  return Array.from({ length: 256 }, (_, i) => [i, i, i] as [number, number, number]);
}

// Pad or trim arrays to exactly 256 entries
function normalize256(data: [number, number, number][]): [number, number, number][] {
  if (data.length === 256) { return data; }
  const result: [number, number, number][] = new Array(256);
  for (let i = 0; i < 256; i++) {
    const srcIdx = Math.round((i / 255) * (data.length - 1));
    result[i] = data[Math.min(srcIdx, data.length - 1)];
  }
  return result;
}

